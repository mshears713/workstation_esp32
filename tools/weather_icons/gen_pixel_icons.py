"""Generate the pixel weather variants in main/weather_icons.c.

First run gen_icons.py if a fresh base is needed, then run this script to
replace six descriptors while retaining fog, snow and the semantic lookup.
Requires Pillow. LVGL images remain ARGB8888 at existing 48/30 dimensions.
"""
from pathlib import Path
import re,hashlib,json
from PIL import Image,ImageDraw

OUT=Path(__file__).resolve().parent/'pixel-art';OUT.mkdir(exist_ok=True)
O=(58,36,32,255); GOLD=(244,190,93,255); LIGHT=(244,226,184,255)
BROWN=(201,149,96,255); PINK=(233,141,156,255); WHITE=(235,227,209,255)
GRAY=(174,170,164,255); BLUE=(111,169,190,255); TRANS=(0,0,0,0)
NAMES=('sun','moon','partly','cloud','rain','storm')

def cloud(draw, y=3, dark=False):
    # 24px native grid, overlapping rounded lobes and a continuous flat base.
    # Integer geometry remains crisp when sampled into existing LVGL sizes.
    for box in ((1,y+7,9,y+15),(4,y+2,15,y+14),(10,y+3,19,y+15),(15,y+7,23,y+15)):
        draw.ellipse(box,fill=O)
    draw.rectangle((3,y+10,21,y+17),fill=O)
    col=GRAY if dark else WHITE
    for box in ((2,y+8,8,y+14),(5,y+3,14,y+13),(11,y+4,18,y+14),(16,y+8,22,y+14)):
        draw.ellipse(box,fill=col)
    draw.rectangle((4,y+10,20,y+15),fill=col)
    draw.rectangle((5,y+15,19,y+15),fill=BROWN if dark else GRAY)

def icon(name):
    grid=16 if name in ('sun','moon') else 24
    im=Image.new('RGBA',(grid,grid),TRANS);d=ImageDraw.Draw(im)
    if name=='sun':
        for x,y in ((7,0),(7,14),(0,7),(14,7),(2,2),(12,2),(2,12),(12,12)):
            d.rectangle((x,y,x+1,y+1),fill=BROWN)
        d.ellipse((3,3,12,12),fill=O);d.ellipse((4,4,11,11),fill=GOLD)
        d.rectangle((5,5,7,6),fill=LIGHT)
    elif name=='moon':
        d.ellipse((2,2,12,13),fill=O);d.ellipse((3,3,11,12),fill=LIGHT)
        d.ellipse((7,1,14,9),fill=TRANS)
        d.rectangle((12,2,13,3),fill=GOLD);d.point((14,5),fill=PINK)
    elif name=='partly':
        # Backend uses this key for daytime partly-cloudy conditions;
        # night conditions keep the existing moon/cloud mapping.
        d.rectangle((6,0,7,2),fill=BROWN);d.rectangle((0,6,2,7),fill=BROWN)
        d.rectangle((15,5,16,7),fill=BROWN)
        d.ellipse((1,1,15,15),fill=O);d.ellipse((2,2,14,14),fill=GOLD)
        d.rectangle((4,4,6,6),fill=LIGHT)
        cloud(d,5)
    elif name=='cloud': cloud(d,3)
    elif name=='rain':
        cloud(d,0,True)
        for x,y in ((5,18),(11,19),(17,18)):
            d.rectangle((x,y,x+1,y+3),fill=BLUE);d.point((x,y+4),fill=LIGHT)
    elif name=='storm':
        cloud(d,0,True)
        d.polygon([(12,15),(8,20),(11,20),(10,23),(17,18),(13,18),(15,15)],fill=O)
        d.polygon([(12,16),(9,19),(12,19),(11,22),(16,18),(12,18)],fill=GOLD)
        # Join the bolt to the cloud so it stays legible at 30 px.
        d.rectangle((11,15,13,17),fill=GOLD)
    else: raise ValueError(name)
    return im

def descriptor(name,size):
    im=icon(name).resize((size,size),Image.Resampling.NEAREST)
    data=[]
    for r,g,b,a in im.getdata(): data.extend((b,g,r,a))
    rows=[', '.join(f'0x{x:02x}' for x in data[i:i+24]) for i in range(0,len(data),24)]
    sym=f'weather_icon_{name}_{size}'
    return (f'static const uint8_t {sym}_map[] = {{\n    '+',\n    '.join(rows)+'\n};\n\n'
      f'const lv_image_dsc_t {sym} = {{\n    .header = {{\n        .magic = LV_IMAGE_HEADER_MAGIC,\n'
      f'        .cf = LV_COLOR_FORMAT_ARGB8888,\n        .w = {size},\n        .h = {size},\n'
      f'        .stride = {size*4},\n    }},\n    .data_size = sizeof({sym}_map),\n    .data = {sym}_map,\n}};\n\n')

target=Path(__file__).resolve().parents[2]/'main'/'weather_icons.c'
source=target.read_text(encoding='utf-8')
source=source.replace('/* GENERATED by tools/weather_icons/gen_icons.py - edit that, not this. */','/* GENERATED by tools/weather_icons/gen_icons.py then gen_pixel_icons.py. */',1)
for name in NAMES:
    icon(name).save(OUT/f'{name}-native.png')
    for size in (48,30):
        sym=f'weather_icon_{name}_{size}'
        pattern=rf'static const uint8_t {sym}_map\[\] = \{{.*?\n\}};\n\nconst lv_image_dsc_t {sym} = \{{.*?\n\}};\n\n'
        source,count=re.subn(pattern,lambda _:descriptor(name,size),source,count=1,flags=re.S)
        assert count==1,(name,size)
target.write_text(source,encoding='utf-8',newline='\n')
(OUT/'manifest.json').write_text(json.dumps({'keys_replaced':NAMES,'untouched_keys':['fog','snow'],'native_grids':{'sun':[16,16],'moon':[16,16],'cloud_variants':[24,24]},'actual_sizes':[48,30],'pixel_bytes_per_icon':4*(48*48+30*30),'six_icon_pixel_bytes':6*4*(48*48+30*30),'baseline_six_icon_pixel_bytes':6*4*(48*48+30*30),'estimated_net_static_image_delta':0,'asset_sha256':{n:hashlib.sha256((OUT/f'{n}-native.png').read_bytes()).hexdigest() for n in NAMES}},indent=2))
print((OUT/'manifest.json').read_text())
